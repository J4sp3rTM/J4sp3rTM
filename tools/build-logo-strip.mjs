// Builds the two logo strips used by README.md.
//
// GitHub loads a CSS reset on profile pages that sets `img,picture{display:block}`
// with an unscoped element selector. A README cannot carry CSS to undo it, so a
// row of separate <img> tags always stacks into a column. One image per row is
// the only layout that survives it, so the logos are composed into a single SVG
// here instead of being listed in the markdown.
//
// Run: node tools/build-logo-strip.mjs

import { writeFileSync } from 'node:fs';

const SIZE = 40;
const GAP = 12;
const BASE = 'https://cdn.jsdelivr.net/gh/devicons/devicon/icons';

const STRIPS = {
  'logos-languages.svg': [
    ['typescript', 'TypeScript'],
    ['python', 'Python'],
    ['java', 'Java'],
    ['kotlin', 'Kotlin'],
    ['csharp', 'C#'],
    ['cplusplus', 'C++'],
    ['html5', 'HTML5'],
    ['css3', 'CSS'],
  ],
  'logos-tools.svg': [
    ['angular', 'Angular'],
    ['react', 'React'],
    ['quarkus', 'Quarkus'],
    ['fastapi', 'FastAPI'],
    ['tauri', 'Tauri'],
    ['godot', 'Godot'],
    ['docker', 'Docker'],
    ['postgresql', 'PostgreSQL'],
  ],
};

/**
 * Each source file has its own ids for gradients, clip paths and masks. Sixteen
 * of them go into one document, so an id that appears in two files makes the
 * second icon reference the first one's paint. Every id gets the icon slug in
 * front of it, and every reference to an id is rewritten to match.
 */
function namespaceIds(markup, slug) {
  const ids = [...markup.matchAll(/\sid="([^"]+)"/g)].map((m) => m[1]);
  let out = markup;
  for (const id of new Set(ids)) {
    const safe = id.replace(/[.*+?^${}()|[\]\\]/g, '\\$&');
    out = out
      .replace(new RegExp(`(\\sid=")${safe}(")`, 'g'), `$1${slug}-${id}$2`)
      .replace(new RegExp(`url\\(#${safe}\\)`, 'g'), `url(#${slug}-${id})`)
      .replace(new RegExp(`((?:xlink:)?href=")#${safe}(")`, 'g'), `$1#${slug}-${id}$2`);
  }
  return out;
}

async function icon(slug) {
  const url = `${BASE}/${slug}/${slug}-original.svg`;
  const res = await fetch(url);
  if (!res.ok) throw new Error(`${slug}: HTTP ${res.status}`);
  const text = await res.text();

  const open = text.match(/<svg\b[^>]*>/i);
  if (!open) throw new Error(`${slug}: no <svg> element`);

  // A nested <svg> scales its content to the box it is given, but only if it
  // knows the coordinate system the artwork was drawn in. Not every icon
  // declares a viewBox, so fall back to its width and height.
  let viewBox = open[0].match(/viewBox="([^"]+)"/i)?.[1];
  if (!viewBox) {
    const w = open[0].match(/\swidth="([\d.]+)/i)?.[1];
    const h = open[0].match(/\sheight="([\d.]+)/i)?.[1];
    if (!w || !h) throw new Error(`${slug}: no viewBox and no size`);
    viewBox = `0 0 ${w} ${h}`;
  }

  const body = text.slice(text.indexOf(open[0]) + open[0].length, text.lastIndexOf('</svg>'));
  return { viewBox, body: namespaceIds(body, slug) };
}

for (const [file, entries] of Object.entries(STRIPS)) {
  const width = entries.length * SIZE + (entries.length - 1) * GAP;
  const parts = [];

  for (const [index, [slug, label]] of entries.entries()) {
    const { viewBox, body } = await icon(slug);
    parts.push(
      `  <svg x="${index * (SIZE + GAP)}" y="0" width="${SIZE}" height="${SIZE}" viewBox="${viewBox}" overflow="visible">\n` +
        `    <title>${label}</title>${body}\n` +
        `  </svg>`,
    );
  }

  const svg = `<svg xmlns="http://www.w3.org/2000/svg" xmlns:xlink="http://www.w3.org/1999/xlink" width="${width}" height="${SIZE}" viewBox="0 0 ${width} ${SIZE}" role="img" aria-label="${entries.map(([, l]) => l).join(', ')}">
<!-- GENERATED by tools/build-logo-strip.mjs. Edit the generator, not this file. -->
${parts.join('\n')}
</svg>
`;

  writeFileSync(new URL(`../${file}`, import.meta.url), svg);
  console.log(file, width + 'x' + SIZE, svg.length + ' bytes');
}
